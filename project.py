def validate_and_predict(features_df, model, scaler, threshold_zero=1e-6):
    """
    Make predictions with domain-specific validation

    In semiconductor manufacturing:
    - All sensors reading 0 = equipment failure or production halt
    - This should be automatically classified as FAIL

    Args:
        features_df: DataFrame of features
        model: Trained model
        scaler: Fitted scaler
        threshold_zero: Threshold below which values are considered zero

    Returns:
        predictions: Array of predictions
        validation_flags: Array indicating which rows were validated
    """
    predictions = []
    validation_flags = []

    for idx in range(len(features_df)):
        row = features_df.iloc[idx]

        # Check for all-zero input (invalid sensor readings)
        if (np.abs(row) < threshold_zero).all():
            print(f"⚠ Row {idx}: All features ≈ 0 → Invalid input → Forcing FAIL prediction")
            predictions.append(1)  # Force FAIL
            validation_flags.append('INVALID_ALL_ZERO')

        # Check for extreme outliers (optional)
        elif (np.abs(row) > 10000).any():
            print(f"⚠ Row {idx}: Extreme values detected → Review required")
            # Still make prediction but flag for review
            scaled = scaler.transform(row.values.reshape(1, -1))
            pred = model.predict(scaled)[0]
            predictions.append(pred)
            validation_flags.append('EXTREME_VALUES')

        else:
            # Normal prediction path
            scaled = scaler.transform(row.values.reshape(1, -1))
            pred = model.predict(scaled)[0]
            predictions.append(pred)
            validation_flags.append('NORMAL')

    return np.array(predictions), np.array(validation_flags)

