def train_and_evaluate(model, param_grid, X_train, y_train, X_test, y_test, model_name):
    """
    Train, tune, and evaluate a model with detailed metrics

    Returns:
        best_model: Trained model with best hyperparameters
        test_accuracy: Accuracy on test set
        metrics_dict: Dictionary containing detailed performance metrics
    """
    print(f"\n{'='*80}")
    print(f"TRAINING AND TUNING: {model_name}")
    print('='*80)

    # Hyperparameter tuning with cross-validation
    grid_search = GridSearchCV(
        model,
        param_grid,
        cv=5,
        scoring='accuracy',
        n_jobs=-1,
        verbose=1
    )
    grid_search.fit(X_train, y_train)

    best_model = grid_search.best_estimator_
    print(f"\nBest hyperparameters: {grid_search.best_params_}")
    print(f"Best CV score: {grid_search.best_score_:.4f}")

    # Make predictions
    y_train_pred = best_model.predict(X_train)
    y_test_pred = best_model.predict(X_test)

    # Calculate metrics
    train_acc = accuracy_score(y_train, y_train_pred)
    test_acc = accuracy_score(y_test, y_test_pred)

    print(f"\n{model_name} Performance:")
    print(f"  Train Accuracy: {train_acc:.4f}")
    print(f"  Test Accuracy: {test_acc:.4f}")

    # Detailed classification report
    print(f"\nClassification Report for {model_name} (Test set):")
    print(classification_report(y_test, y_test_pred,
                                target_names=['Pass (-1)', 'Fail (1)']))

    # Confusion matrix
    cm = confusion_matrix(y_test, y_test_pred)
    plt.figure(figsize=(8, 6))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues',
                xticklabels=['Pass', 'Fail'],
                yticklabels=['Pass', 'Fail'])
    plt.title(f'{model_name} Confusion Matrix (Test Set)')
    plt.xlabel('Predicted')
    plt.ylabel('Actual')
    plt.tight_layout()
    plt.show()

    # Extract key metrics for FAIL class (class 1)
    from sklearn.metrics import precision_recall_fscore_support
    precision, recall, f1, _ = precision_recall_fscore_support(
        y_test, y_test_pred, average=None, labels=[1]
    )

    metrics_dict = {
        'train_accuracy': train_acc,
        'test_accuracy': test_acc,
        'fail_precision': precision[0],
        'fail_recall': recall[0],
        'fail_f1': f1[0]
    }

    return best_model, test_acc, metrics_dict

